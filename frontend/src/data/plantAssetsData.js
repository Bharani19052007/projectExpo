// Live Process Telemetry Time-Series Buffer Generator
export const generateLiveTelemetryBuffer = (asset, points = 20) => {
  const now = Date.now();
  const buffer = [];
  const baseTemp = asset?.temperature || 60;
  const basePress = typeof asset?.pressure === 'number' ? asset.pressure : 20;
  const baseVib = asset?.vibration || 1.2;

  for (let i = points - 1; i >= 0; i--) {
    const timestamp = new Date(now - i * 3000);
    const timeStr = timestamp.toTimeString().substring(0, 8);
    const noiseT = (Math.sin(i * 0.6) + (Math.random() - 0.5) * 0.4) * (baseTemp * 0.02);
    const noiseP = (Math.cos(i * 0.5) + (Math.random() - 0.5) * 0.3) * (basePress * 0.015);
    const noiseV = (Math.sin(i * 0.8) + (Math.random() - 0.5) * 0.4) * (baseVib * 0.05);

    buffer.push({
      time: timeStr,
      temp: Number((baseTemp + noiseT).toFixed(1)),
      pressure: Number((basePress + noiseP).toFixed(2)),
      vibration: Number((baseVib + noiseV).toFixed(2)),
      flow: asset?.flowRate ? Number((asset.flowRate + (Math.random() - 0.5) * 5).toFixed(1)) : 0,
      power: asset?.power ? Number((asset.power + (Math.random() - 0.5) * 2).toFixed(1)) : 0,
    });
  }
  return buffer;
};

